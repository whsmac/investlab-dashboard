-- INVESTLAB instrument registry and transaction ledger
-- Apply manually in Supabase SQL Editor after reviewing.
-- Does not alter or delete the existing public.holdings table.

create table if not exists public.instruments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  symbol text not null check (symbol = upper(symbol) and symbol ~ '^[A-Z0-9][A-Z0-9.-]{0,19}$'),
  display_name text not null default '',
  list_type text not null check (list_type in ('watchlist', 'holding', 'past')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, symbol, list_type)
);

create index if not exists instruments_user_type_idx
  on public.instruments (user_id, list_type, symbol);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  symbol text not null check (symbol = upper(symbol) and symbol ~ '^[A-Z0-9][A-Z0-9.-]{0,19}$'),
  transaction_type text not null check (transaction_type in ('buy', 'sell', 'dividend', 'fee')),
  traded_at timestamptz not null,
  quantity numeric(20,8) not null default 0 check (quantity >= 0),
  price numeric(20,8) not null default 0 check (price >= 0),
  fees numeric(20,8) not null default 0 check (fees >= 0),
  account_name text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists transactions_user_date_idx
  on public.transactions (user_id, traded_at desc);
create index if not exists transactions_user_symbol_idx
  on public.transactions (user_id, symbol, traded_at);

alter table public.instruments enable row level security;
alter table public.transactions enable row level security;

drop policy if exists "Users manage own instruments" on public.instruments;
create policy "Users manage own instruments"
  on public.instruments for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users manage own transactions" on public.transactions;
create policy "Users manage own transactions"
  on public.transactions for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant select, insert, update, delete on public.instruments to authenticated;
grant select, insert, update, delete on public.transactions to authenticated;
grant usage, select on sequence public.instruments_id_seq to authenticated;
grant usage, select on sequence public.transactions_id_seq to authenticated;
