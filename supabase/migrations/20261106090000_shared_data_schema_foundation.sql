-- INVESTLAB shared public-company data foundation.
-- Draft only: review and apply manually to the isolated investlab-ledger-test project.
-- No owner is seeded here. Writes remain disabled until the verified auth user UUID
-- is explicitly added to app_private.data_owners after read-only preflight.

begin;

create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;
grant usage on schema app_private to authenticated;

create table if not exists app_private.data_owners (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
revoke all on table app_private.data_owners from public, anon, authenticated;

create or replace function app_private.is_data_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from app_private.data_owners as owner_record
    where owner_record.user_id = (select auth.uid())
  );
$$;
revoke all on function app_private.is_data_owner() from public, anon;
grant execute on function app_private.is_data_owner() to authenticated;

create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  ticker text not null unique
    check (ticker = upper(ticker) and ticker ~ '^[A-Z0-9][A-Z0-9.-]{0,19}$'),
  company_name text not null check (length(trim(company_name)) > 0),
  exchange text,
  listing_date date,
  fiscal_year_end_month smallint
    check (fiscal_year_end_month between 1 and 12),
  is_active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.import_batches (
  id bigint generated by default as identity primary key,
  dataset_type text not null
    check (dataset_type in ('market_price', 'quarterly_financial')),
  source_name text,
  source_url text check (source_url is null or source_url ~ '^https://'),
  file_name text,
  status text not null default 'staged'
    check (status in ('staged', 'validated', 'committed', 'rejected')),
  row_count integer not null default 0 check (row_count >= 0),
  accepted_count integer not null default 0 check (accepted_count >= 0),
  rejected_count integer not null default 0 check (rejected_count >= 0),
  submitted_by uuid not null references auth.users(id),
  notes text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  check (accepted_count + rejected_count <= row_count)
);

create table if not exists public.market_price_observations (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  trading_date date not null,
  price_basis text not null default 'adjusted_close'
    check (price_basis in ('adjusted_close')),
  close_price numeric(20,8) not null check (close_price > 0),
  currency char(3) not null default 'USD'
    check (currency = upper(currency)),
  import_batch_id bigint not null references public.import_batches(id) on delete restrict,
  source_url text check (source_url is null or source_url ~ '^https://'),
  created_at timestamptz not null default now(),
  unique (company_id, trading_date, price_basis)
);
create index if not exists market_price_observations_date_idx
  on public.market_price_observations (trading_date, company_id);

create table if not exists public.quarterly_financial_observations (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  fiscal_period text not null
    check (fiscal_period ~ '^[0-9]{4}-Q[1-4]$'),
  revision_number integer not null default 1 check (revision_number > 0),
  is_current boolean not null default true,
  revenue_usd_bn numeric(24,8) check (revenue_usd_bn is null or revenue_usd_bn >= 0),
  capex_usd_bn numeric(24,8) check (capex_usd_bn is null or capex_usd_bn >= 0),
  capex_definition text,
  source_url text check (source_url is null or source_url ~ '^https://'),
  import_batch_id bigint not null references public.import_batches(id) on delete restrict,
  notes text,
  created_at timestamptz not null default now(),
  check (revenue_usd_bn is not null or capex_usd_bn is not null),
  check (capex_usd_bn is null or length(trim(coalesce(capex_definition, ''))) > 0),
  unique (company_id, fiscal_period, revision_number)
);
create unique index if not exists quarterly_financial_one_current_idx
  on public.quarterly_financial_observations (company_id, fiscal_period)
  where is_current;
create index if not exists quarterly_financial_period_idx
  on public.quarterly_financial_observations (fiscal_period, company_id);

alter table public.companies enable row level security;
alter table public.import_batches enable row level security;
alter table public.market_price_observations enable row level security;
alter table public.quarterly_financial_observations enable row level security;

drop policy if exists "Authenticated users read companies" on public.companies;
create policy "Authenticated users read companies"
  on public.companies for select to authenticated using (true);
drop policy if exists "Owners manage companies" on public.companies;
create policy "Owners manage companies"
  on public.companies for all to authenticated
  using ((select app_private.is_data_owner()))
  with check ((select app_private.is_data_owner()));

drop policy if exists "Authenticated users read import batches" on public.import_batches;
create policy "Authenticated users read import batches"
  on public.import_batches for select to authenticated using (true);
drop policy if exists "Owners manage import batches" on public.import_batches;
create policy "Owners manage import batches"
  on public.import_batches for all to authenticated
  using ((select app_private.is_data_owner()))
  with check (
    (select app_private.is_data_owner())
    and submitted_by = (select auth.uid())
  );

drop policy if exists "Authenticated users read market prices" on public.market_price_observations;
create policy "Authenticated users read market prices"
  on public.market_price_observations for select to authenticated using (true);
drop policy if exists "Owners manage market prices" on public.market_price_observations;
create policy "Owners manage market prices"
  on public.market_price_observations for all to authenticated
  using ((select app_private.is_data_owner()))
  with check ((select app_private.is_data_owner()));

drop policy if exists "Authenticated users read quarterly financials" on public.quarterly_financial_observations;
create policy "Authenticated users read quarterly financials"
  on public.quarterly_financial_observations for select to authenticated using (true);
drop policy if exists "Owners manage quarterly financials" on public.quarterly_financial_observations;
create policy "Owners manage quarterly financials"
  on public.quarterly_financial_observations for all to authenticated
  using ((select app_private.is_data_owner()))
  with check ((select app_private.is_data_owner()));

grant select, insert, update, delete on
  public.companies,
  public.import_batches,
  public.market_price_observations,
  public.quarterly_financial_observations
to authenticated;

grant usage, select on sequence
  public.companies_id_seq,
  public.import_batches_id_seq,
  public.market_price_observations_id_seq,
  public.quarterly_financial_observations_id_seq
to authenticated;

commit;
